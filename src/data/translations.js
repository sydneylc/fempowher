export function isRtlLanguage(lang = 'en', writtenLanguage = '') {
  const rtlCodes = new Set(['prs', 'fa', 'ps', 'ur', 'ar', 'ku', 'bal', 'rhg', 'he', 'yi', 'ug', 'sd']);
  if (rtlCodes.has(String(lang || '').toLowerCase())) return true;
  const langObj = LANGUAGES.find((l) => l.code === lang);
  if (langObj && langObj.dir === 'rtl') return true;
  const s = String(writtenLanguage || '').trim().toLowerCase();
  if (!s) return false;
  if (s.includes('mandarin') || s.includes('manderin') || s.includes('chin')) return false;
  return /\bdari\b|farsi|persian|pashto|pushto|arabic|urdu|baloch|kurd|sorani|rohingya|hebrew|yiddish|uyghur|sindhi|پښتو|دری|فارسی|العربية|اردو|بلوچی|کوردی/i.test(
    s
  );
}

export function cleanBackLabel(rawLabel, lang = 'en') {
  const fallback = UI_TEXT[lang]?.backBtn || UI_TEXT.en.backBtn || 'Back';
  const base = String(rawLabel || fallback)
    .replace(/[←→]/g, '')
    .trim();
  return base || 'Back';
}
