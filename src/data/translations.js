// Automatically detects the user's phone/computer system language (navigator.languages / navigator.language)
// Defaults to 'en'on your English Mac, or 'ar'if a user's phone is in Arabic, 'bn'for Bangla, 'so'for Somali, etc.
export function detectDeviceLanguage() {
  try {
    const rawList =
      navigator.languages && navigator.languages.length > 0
        ? navigator.languages
        : [navigator.language || 'en'];
    for (const locale of rawList) {
      const short = String(locale).toLowerCase().split('-')[0];
      if (LANGUAGES.some((l) => l.code === short)) {
        return short;
      }
    }
  } catch (e) {}
  return 'en';
}

// ============================================================================
// UserLanguageChoice1:
// Global variable/helper representing the user's active language preference.
// Any title, heading, or text subject to UserLanguageChoice1 automatically
// switches to the user's chosen language (e.g. Arabic 'ar', Amharic 'am',
// Spanish 'es', Somali 'so', Bangla 'bn', Rohingya 'rhg', or any of the 250+
// world languages).
// ============================================================================
export function resolveUserLanguageChoice1(lang = 'en', writtenLanguage = 'English', activeUiDict = null) {
  const uiCode = lang || mapWrittenLanguageToUiCode(writtenLanguage) || 'en';
  const tlTarget = mapWrittenLanguageToTranslateTarget(writtenLanguage) || (uiCode !== 'en' ? uiCode : 'en');
  const dict = activeUiDict || UI_TEXT[uiCode] || UI_TEXT.en;

  return {
    code: uiCode,
    writtenLanguage: writtenLanguage || 'English',
    translateTarget: tlTarget,
    t: dict,
    // Allows `obj[UserLanguageChoice1]` or `${UserLanguageChoice1}` to evaluate to the language code (e.g. 'ar', 'am')
    toString() {
      return uiCode;
    },
    valueOf() {
      return uiCode;
    },
    // Translates a dictionary object `{ en, ar, am, ... }`, a UI_TEXT key, or fallback text into UserLanguageChoice1
    translate(valueOrKey, fallbackEn = '') {
      if (!valueOrKey) return fallbackEn;
      if (typeof valueOrKey === 'object') {
        return valueOrKey[uiCode] || valueOrKey.en || fallbackEn;
      }
      if (typeof valueOrKey === 'string') {
        if (dict && dict[valueOrKey]) {
          return dict[valueOrKey];
        }
        return fallbackEn || valueOrKey;
      }
      return fallbackEn;
    }
  };
}

